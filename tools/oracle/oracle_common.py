"""Shared helpers of the golden-oracle exporters (tools/oracle/export_*.py).

Paths, the 1.17.0.1 profile identity, hashing of evidence files, and rendering of
plain Python data as Lua table literals that tests load with ``loadstring``.
"""
from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EVIDENCE = ROOT / "docs" / "research" / "evidence"
GOLDEN = ROOT / "tests" / "golden" / "oracle"
PROFILE = ROOT / "defs" / "profile" / "bw-1.17.0.1.json"
TARGET_SHA256 = "94dea44898a3934cdfae2a8149c0044db8ad1af4b4bc54306cdca3b1612d6ed0"

_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_LUA_KEYWORDS = frozenset(
    "and break do else elseif end false for function if in local nil not or repeat return then true until while".split()
)


class ExportError(SystemExit):
    """Raised when evidence does not satisfy the expectations of an exporter."""


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def canonical_sha256(value: object) -> str:
    """SHA-256 of the canonical JSON form (sorted keys, no whitespace)."""
    return sha256_bytes(json.dumps(value, sort_keys=True, separators=(",", ":")).encode())


def load_evidence(name: str) -> tuple[dict, str]:
    """Load an evidence JSON; reject it when it names another executable than the profile's."""
    path = EVIDENCE / name
    raw = path.read_bytes()
    data = json.loads(raw)
    target = data.get("target_sha256")
    if target is not None and target != TARGET_SHA256:
        raise ExportError(f"{name}: target {target} is not the 1.17.0.1 profile executable")
    return data, sha256_bytes(raw)


def lua(value: object) -> str:
    """Render JSON-like data as a Lua literal. ``None`` is allowed only as a table value
    (the key is then omitted); a list may not contain ``None``."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, (list, tuple)):
        if any(v is None for v in value):
            raise TypeError(f"list with nil element: {value!r}")
        return "{" + ", ".join(lua(v) for v in value) + "}"
    if isinstance(value, dict):
        parts = []
        for k, v in value.items():
            if v is None:
                continue
            if isinstance(k, int):
                key = f"[{k}]"
            elif _IDENT.match(k) and k not in _LUA_KEYWORDS:
                key = k
            else:
                key = f"[{json.dumps(k)}]"
            parts.append(f"{key} = {lua(v)}")
        return "{" + ", ".join(parts) + "}"
    raise TypeError(f"unsupported value {value!r}")


def render_module(generator: str, header: dict, cases: list) -> str:
    """A Lua module returning ``header`` fields plus a ``cases`` array, one case per line."""
    lines = [f"-- Generated by {generator}; do not edit.", "return {"]
    for k, v in header.items():
        lines.append(f"\t{k} = {lua(v)},")
    lines.append("\tcases = {")
    lines += [f"\t\t{lua(c)}," for c in cases]
    lines += ["\t},", "}", ""]
    return "\n".join(lines)
