#!/usr/bin/env python3
"""Writes native/kp_core/src/core/kp_crc32_table.h, the slicing-by-8 tables of kp_kpf.c's CRC-32 (IEEE, reflected
0xedb88320): table k gives the CRC of a byte followed by k zero bytes. Constant tables need no lazy initialization,
so games on several threads share them safely. --check fails when the header is out of date."""
from __future__ import annotations

import argparse
import logging
import sys
from pathlib import Path

HEADER = Path(__file__).resolve().parents[2] / "native/kp_core/src/core/kp_crc32_table.h"
POLYNOMIAL = 0xEDB88320
TABLES = 8
BYTES = 256
PER_LINE = 6

log = logging.getLogger("crc32_table")


def tables() -> list[list[int]]:
    first = []
    for n in range(BYTES):
        v = n
        for _ in range(8):
            v = POLYNOMIAL ^ (v >> 1) if v & 1 else v >> 1
        first.append(v)
    out = [first]
    for _ in range(1, TABLES):
        prev = out[-1]
        out.append([(prev[n] >> 8) ^ first[prev[n] & 0xFF] for n in range(BYTES)])
    return out


def render() -> str:
    lines = [
        "/* Generated by tools/native/crc32_table.py: do not edit. The slicing-by-8 tables of kp_kpf.c's CRC-32 (IEEE,",
        " * reflected 0xedb88320): table k gives the CRC of a byte followed by k zero bytes. */",
        "#ifndef KP_CRC32_TABLE_H",
        "#define KP_CRC32_TABLE_H",
        "",
        f"static const uint32_t KP_CRC32_TABLE[{TABLES}][{BYTES}] = {{",
    ]
    for table in tables():
        lines.append("\t{")
        for at in range(0, BYTES, PER_LINE):
            lines.append("\t\t" + " ".join(f"0x{v:08x}u," for v in table[at:at + PER_LINE]))
        lines.append("\t},")
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the header is out of date")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not HEADER.exists() or HEADER.read_text() != text:
            log.error("%s is out of date: run tools/native/crc32_table.py", HEADER)
            return 1
        return 0
    HEADER.write_text(text)
    log.info("wrote %s", HEADER)
    return 0


if __name__ == "__main__":
    sys.exit(main())
