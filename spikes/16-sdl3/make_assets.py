"""Writes assets.h for spike 16: an 8-bit grayscale PNG, an 8-bit paletted PNG with the same
index pattern, and one OGG from the converted sound packs, as C byte arrays.

Usage: python3 spikes/16-sdl3/make_assets.py OGG OUT_HEADER
"""
from __future__ import annotations

import struct
import sys
import zlib
from pathlib import Path

WIDTH = 64
HEIGHT = 48


def index(x: int, y: int) -> int:
    return (x * 5 + y * 3) & 255


def chunk(kind: bytes, data: bytes) -> bytes:
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))


def png(colour_type: int, extra: bytes) -> bytes:
    rows = b"".join(b"\0" + bytes(index(x, y) for x in range(WIDTH)) for y in range(HEIGHT))
    header = struct.pack(">IIBBBBB", WIDTH, HEIGHT, 8, colour_type, 0, 0, 0)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + extra
            + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b""))


def c_array(name: str, data: bytes) -> str:
    body = ",".join(str(b) for b in data)
    return f"static const unsigned char {name}[{len(data)}] = {{{body}}};\n"


def main() -> None:
    ogg, out = Path(sys.argv[1]), Path(sys.argv[2])
    palette = bytes(c for i in range(256) for c in ((i * 3) & 255, (i * 5 + 17) & 255, 255 - i))
    text = (
        "// Generated by spikes/16-sdl3/make_assets.py; do not edit.\n"
        f"#define ASSET_PNG_W {WIDTH}\n#define ASSET_PNG_H {HEIGHT}\n"
        "static inline unsigned char asset_png_index(int x, int y) { return (unsigned char)((x * 5 + y * 3) & 255); }\n"
        + c_array("asset_png_gray", png(0, b""))
        + c_array("asset_png_palette", png(3, chunk(b"PLTE", palette)))
        + c_array("asset_ogg", ogg.read_bytes())
    )
    out.write_text(text)


if __name__ == "__main__":
    main()
